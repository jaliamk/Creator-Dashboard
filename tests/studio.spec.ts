test('default production flow synchronizes daily times and preserves publication counts', async ({ page }) => {
  test.skip(!process.env.E2E_SUPABASE, 'Requires disposable Supabase')
  test.setTimeout(90000)
  await page.setViewportSize({width:1500,height:900})
  await page.goto('/')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.getByRole('button',{name:'Create an account'}).click()
  await page.getByLabel('Email').fill(`workflow-${Date.now()}@example.com`)
  await page.getByLabel('Password').fill('Playwright-test-9473')
  await page.getByRole('button',{name:'Create account',exact:true}).click()
  await expect(page.getByRole('button',{name:'Sign out'})).toBeVisible()
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.getByLabel('Project name').fill('Studio update')
  await expect(page.getByLabel('Project template')).toHaveValue(/.+/)
  await page.getByRole('button',{name:'Create project',exact:true}).click()
  await expect(page.locator('.kanban-card')).toHaveCount(5)
  await expect(page.getByRole('heading',{name:/Blocked/})).toHaveCount(0)
  await page.getByRole('button',{name:'Project timeline',exact:true}).click()
  const timeline=page.getByRole('region',{name:'Project timeline'})
  const phase=timeline.locator('.gantt-stage').getByRole('button',{name:'Edit dates for Editing',exact:true})
  const task=timeline.locator('.gantt-line:not(.gantt-stage)').getByRole('button',{name:'Edit dates for Editing',exact:true})
  await task.click()
  const dialog=page.getByRole('dialog')
  const day=new Date().toISOString().slice(0,10)
  const tomorrow=new Date(Date.parse(day)+86400000).toISOString().slice(0,10)
  await dialog.getByLabel('Start date').fill(day)
  await dialog.getByLabel('End date').fill(tomorrow)
  await dialog.getByRole('button',{name:'Save dates'}).click()
  await expect(page.getByText('Timeline updated.',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Calendar',exact:true}).click()
  const calendar=page.getByRole('region',{name:'Weekly production calendar'})
  const today=calendar.locator('.calendar-current')
  const entry=today.locator('.calendar-event').filter({hasText:'Editing'})
  await expect(entry).toHaveCount(1)
  await expect(entry).toContainText('All day')
  await entry.click()
  await dialog.getByLabel('Start time').fill('14:00')
  await dialog.getByLabel('Duration (minutes)').fill('75')
  await dialog.getByRole('button',{name:'Save time'}).click()
  await expect(entry).toContainText(/2:00 PM.*3:15 PM/)
  await page.getByRole('button',{name:'Time grid',exact:true}).click()
  const edge=today.locator('.calendar-timed').filter({hasText:'Editing'}).locator('.calendar-resize.end')
  await edge.evaluate(element=>element.scrollIntoView({block:'center',inline:'center'}))
  const box=await edge.boundingBox()
  await page.mouse.move(box!.x+box!.width/2,box!.y+3)
  await page.mouse.down()
  await page.mouse.move(box!.x+box!.width/2,box!.y+21,{steps:5})
  await page.mouse.up()
  await expect(entry).not.toContainText('3:15 PM')
  await page.getByRole('button',{name:'Projects',exact:true}).click()
  const card=page.getByRole('button',{name:'Open Studio update',exact:true})
  await card.click()
  await page.getByRole('button',{name:'Project timeline',exact:true}).click()
  await task.click()
  await expect(dialog.getByLabel('Start date')).toHaveValue(day)
  await expect(dialog.getByLabel('End date')).toHaveValue(tomorrow)
  await dialog.getByLabel('End date').fill(day)
  await dialog.getByRole('button',{name:'Save dates'}).click()
  await expect(page.getByText('Timeline updated.',{exact:true})).toBeVisible()
  await expect(phase).toBeVisible()
  await page.getByRole('button',{name:'All projects',exact:true}).click()
  await card.dragTo(page.getByRole('region',{name:'Published',exact:true}).getByRole('heading'))
  await expect(page.getByLabel('Stage for Studio update')).toHaveValue('published')
  await page.getByRole('button',{name:'Creator Journey',exact:true}).click()
  await expect(page.getByRole('article').filter({hasText:'Long-form videos published'})).toContainText('1')
  await page.getByRole('button',{name:'Projects',exact:true}).click()
  await page.getByLabel('Options for Studio update').click()
  await page.getByRole('button',{name:'Delete project',exact:true}).click()
  await expect(dialog).toContainText('Logged time and publication history will be kept.')
  await dialog.getByRole('button',{name:'Delete project',exact:true}).click()
  await page.reload()
  await page.getByRole('button',{name:'Creator Journey',exact:true}).click()
  await expect(page.getByRole('article').filter({hasText:'Long-form videos published'})).toContainText('1')
  await expect(page.getByRole('heading',{name:'Published work'})).toBeVisible()
})
