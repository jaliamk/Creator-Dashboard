import { expect, test } from '@playwright/test'

test('overview adapts to a phone and applies dark appearance', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Studio overview' })).toBeVisible()
  await expect(page.getByRole('progressbar')).toHaveCount(7)
  expect(await page.locator('body').evaluate(body => body.scrollWidth)).toBeLessThanOrEqual(375)
  await page.getByRole('button', { name: 'Settings' }).click()
  await page.getByLabel('Appearance').selectOption('dark')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
})

test('sign up, earn and correct XP, export, and delete a project', async ({ page }) => {
  test.skip(!process.env.E2E_SUPABASE, 'Requires a disposable Supabase instance with email confirmations disabled')
  const email = `studio-${Date.now()}@example.com`
  await page.goto('/')
  await page.getByRole('button', { name: 'New project' }).click()
  await page.getByRole('button', { name: 'Create an account' }).click()
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password').fill('Playwright-test-9473')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible()
  await expect(page.getByText('Loading your workspace…')).toHaveCount(0)
  await page.getByRole('button', { name: 'New project' }).click()
  await page.getByLabel('Project name').fill('Field notes')
  await page.getByRole('button', { name: 'Create project' }).click()
  await expect(page.getByRole('heading', { name: 'Field notes' })).toBeVisible()
  await page.getByRole('button', { name: 'New task' }).click()
  await page.getByLabel('Task title').fill('Cut the intro')
  await page.getByRole('button', { name: 'Create task' }).click()
  await page.getByRole('button', { name: 'Complete Cut the intro' }).click()
  await expect(page.getByRole('button', { name: 'Reopen Cut the intro' })).toBeVisible()

  await page.getByRole('button', { name: 'Work sessions', exact: true }).click()
  await page.getByRole('button', { name: 'Start timer' }).click()
  await page.getByRole('button', { name: /Stop ·/ }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByLabel('Task').selectOption({ label: 'Cut the intro' })
  await page.getByLabel('Whole minutes').fill('120')
  await page.getByRole('button', { name: 'Preview XP' }).click()
  await expect(page.getByText('+100 Creator XP · +100 Editing XP')).toBeVisible()
  await page.getByRole('button', { name: 'Save session' }).click()
  await expect(page.getByText('120 min · Editing')).toBeVisible()

  await page.getByRole('button', { name: 'Overview' }).click()
  await expect(page.getByRole('heading', { name: 'Level 2', exact: true })).toBeVisible()
  await expect(page.getByText('110 total XP')).toBeVisible()
  await page.getByRole('button', { name: 'Work sessions', exact: true }).click()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Whole minutes').fill('30')
  await page.getByRole('button', { name: 'Preview XP' }).click()
  await expect(page.getByText('+30 Creator XP · +30 Editing XP')).toBeVisible()
  await page.getByRole('button', { name: 'Save session' }).click()
  await expect(page.getByText('30 min · Editing')).toBeVisible()

  await page.reload()
  await expect(page.getByText('40 total XP')).toBeVisible()
  await page.getByRole('button', { name: 'Settings' }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export JSON' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('creator-studio-export.json')
  const stream = await download.createReadStream()
  let json = ''
  for await (const chunk of stream) json += chunk
  expect(JSON.parse(json).ledger).toHaveLength(2)

  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await page.getByRole('button', { name: /Field notes/ }).click()
  await page.getByRole('button', { name: 'Reopen Cut the intro' }).click()
  await expect(page.getByRole('button', { name: 'Complete Cut the intro' })).toBeVisible()
  await page.getByRole('button', { name: 'Edit project' }).click()
  await page.getByLabel('Archive project').check()
  await page.getByRole('button', { name: 'Save project' }).click()
  await expect(page.getByText('Archived', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit project' }).click()
  await page.getByRole('button', { name: 'Delete project' }).click()
  await page.getByRole('button', { name: 'Delete project' }).click()
  await expect(page.getByText('Nothing archived')).toBeVisible()
  await page.getByRole('button', { name: 'Overview' }).click()
  await expect(page.getByText('0 total XP')).toBeVisible()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByText('Sign in to save projects and start earning XP.')).toBeVisible()
})
