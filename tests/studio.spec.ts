import { expect, test, type Page } from '@playwright/test'

async function signup(page: Page) {
  await page.goto('/')
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.getByRole('button',{name:'Create an account'}).click()
  await page.getByLabel('Email').fill(`simple-${crypto.randomUUID()}@example.com`)
  await page.getByLabel('Password').fill('Playwright-test-9473')
  await page.getByRole('button',{name:'Create account',exact:true}).click()
  await expect(page.getByRole('button',{name:'Sign out'})).toBeVisible()
}

async function createProject(page: Page, title: string) {
  await page.getByRole('button',{name:'New project',exact:true}).click()
  await page.getByLabel('Project name').fill(title)
  await page.getByRole('button',{name:'Create project',exact:true}).click()
  await expect(page.getByRole('heading',{name:title,exact:true})).toBeVisible()
}

test('portfolio adapts to a phone and applies dark appearance', async ({ page }) => {
  await page.setViewportSize({ width:375,height:812 })
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Projects',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Calendar',exact:true}).click()
  await expect(page.getByRole('region',{name:'Weekly production calendar'})).toBeVisible()
  expect(await page.locator('body').evaluate(body => body.scrollWidth)).toBeLessThanOrEqual(375)
  await page.getByRole('button',{name:'Settings'}).click()
  await page.getByLabel('Appearance').selectOption('dark')
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
})

test('moves project and task cards, completes quests, and publishes without leaving active planning behind', async ({ page }) => {
  test.skip(!process.env.E2E_SUPABASE,'Requires disposable Supabase')
  test.setTimeout(85000)
  await page.setViewportSize({width:1500,height:900})
  await signup(page)
  await createProject(page,'Studio release')
  await expect(page.locator('.kanban-card')).toHaveCount(5)
  await page.getByRole('button',{name:'All projects',exact:true}).click()
  const card = page.getByRole('button',{name:'Open Studio release',exact:true})
  await card.dragTo(page.getByRole('region',{name:'Editing',exact:true}).getByRole('heading'))
  await expect(page.getByLabel('Stage for Studio release')).toHaveValue('editing')
  await expect(page.getByText('60% of production complete')).toBeVisible()
  await card.click()
  const editing = page.locator('.kanban-card').filter({has:page.getByRole('button',{name:'Editing',exact:true})})
  await editing.dragTo(page.locator('.column-done').getByRole('heading'))
  await expect(page.getByText('4 of 5 stages complete')).toBeVisible()
  await page.getByRole('button',{name:'All projects',exact:true}).click()
  await expect(page.getByLabel('Stage for Studio release')).toHaveValue('preparing')
  await page.getByLabel('Stage for Studio release').selectOption('scriptwriting')
  await expect(page.getByText('80% of production complete')).toBeVisible()
  await page.getByRole('button',{name:'Quick Quests',exact:true}).click()
  const quest = page.getByRole('button',{name:'Complete 25 minutes of editing',exact:true})
  await quest.click()
  await expect(page.getByText('25 minutes of editing completed.',{exact:true})).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button',{name:'Undo 25 minutes of editing'}).click()
  await expect(page.getByText('Quest completion undone.')).toBeVisible()
  await quest.click()
  await page.getByRole('button',{name:'Projects',exact:true}).click()
  await page.getByLabel('Stage for Studio release').selectOption('published')
  await expect(page.getByText('Project marked published.')).toBeVisible()
  await page.getByRole('button',{name:'Timeline',exact:true}).click()
  await expect(page.getByText('No active projects to plan.')).toBeVisible()
  await page.getByRole('button',{name:'Creator Journey',exact:true}).click()
  await expect(page.getByRole('article').filter({hasText:'Long-form videos published'})).toContainText('1')
  await expect(page.getByRole('article').filter({hasText:'Creative work sessions completed'})).toContainText('1')
  await page.getByRole('button',{name:'Projects',exact:true}).click()
  await page.getByLabel('Stage for Studio release').selectOption('editing')
  await page.getByRole('button',{name:'Timeline',exact:true}).click()
  await expect(page.getByRole('button',{name:'Studio release',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Projects',exact:true}).click()
  await page.getByLabel('Options for Studio release').click()
  await page.getByRole('button',{name:'Archive project',exact:true}).click()
  await page.getByRole('button',{name:'Show archive',exact:true}).click()
  await expect(card).toBeVisible()
})

test('shares one timed calendar entry per stage and contains Gantt scrolling', async ({page}) => {
  test.skip(!process.env.E2E_SUPABASE,'Requires disposable Supabase')
  test.setTimeout(90000)
  await signup(page)
  await createProject(page,'Schedule test')
  await page.getByRole('button',{name:'Project timeline',exact:true}).click()
  const timeline = page.getByRole('region',{name:'Project timeline'})
  const viewport = timeline.getByLabel('Scrollable production timeline',{exact:true})
  const slider = timeline.getByRole('slider',{name:'Scroll timeline horizontally'})
  for (const width of [1500,1024,390]) {
    await page.setViewportSize({width,height:360})
    await expect(slider).toBeVisible()
    const result = await viewport.evaluate(element => {
      element.scrollTo(210,110)
      const root = element.getBoundingClientRect()
      const axis = element.querySelector('.gantt-axis')!.getBoundingClientRect()
      const label = element.querySelectorAll('.gantt-line')[2].querySelector('.gantt-label')!.getBoundingClientRect()
      return {pageWidth:document.documentElement.scrollWidth,windowWidth:document.documentElement.clientWidth,
        horizontal:element.scrollLeft,vertical:element.scrollTop,top:Math.abs(axis.top-root.top),left:Math.abs(label.left-root.left)}
    })
    expect(result.pageWidth).toBe(result.windowWidth)
    expect(result.horizontal).toBeGreaterThan(0)
    expect(result.vertical).toBeGreaterThan(0)
    expect(result.top).toBeLessThan(2)
    expect(result.left).toBeLessThan(2)
    await slider.press('Home')
    await expect.poll(()=>viewport.evaluate(element=>element.scrollLeft)).toBe(0)
    await slider.press('ArrowRight')
    await expect.poll(()=>viewport.evaluate(element=>element.scrollLeft)).toBeGreaterThan(0)
    await timeline.getByRole('button',{name:'Today',exact:true}).click()
  }
  await page.setViewportSize({width:1500,height:900})
  const dialog = page.getByRole('dialog')
  const day = new Date().toISOString().slice(0,10)
  await timeline.getByRole('button',{name:'Edit dates for Editing',exact:true}).click()
  await dialog.getByLabel('Start date').fill(day)
  await dialog.getByLabel('End date').fill(day)
  await dialog.getByRole('button',{name:'Save dates'}).click()
  await expect(page.getByText('Timeline updated.',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Calendar',exact:true}).click()
  const calendar = page.getByRole('region',{name:'Weekly production calendar'})
  const today = calendar.locator('.calendar-current')
  const entry = today.locator('.calendar-event').filter({hasText:'Editing'})
  await expect(entry).toHaveCount(1)
  await entry.click()
  await dialog.getByLabel('Start time').fill('14:00')
  await dialog.getByLabel('Duration (minutes)').fill('75')
  await dialog.getByRole('button',{name:'Save time'}).click()
  await expect(entry).toContainText(/2:00 PM.*3:15 PM/)
  const next = await calendar.locator('.calendar-current + .calendar-day').count() > 0
  const destination = calendar.locator(next ? '.calendar-current + .calendar-day' : '.calendar-day:has(+ .calendar-current)')
  await entry.dragTo(destination.locator('header'))
  await expect(destination.locator('.calendar-event').filter({hasText:'Editing'})).toContainText(/2:00 PM.*3:15 PM/)
  await expect(entry).toHaveCount(0)
  await page.getByRole('button',{name:'Projects',exact:true}).click()
  await page.getByRole('button',{name:'Open Schedule test',exact:true}).click()
  await page.getByRole('button',{name:'Project timeline',exact:true}).click()
  await timeline.getByRole('button',{name:'Edit dates for Editing',exact:true}).click()
  const shifted = new Date(Date.parse(day)+(next?1:-1)*86400000).toISOString().slice(0,10)
  await expect(dialog.getByLabel('Start date')).toHaveValue(shifted)
  await expect(dialog.getByLabel('End date')).toHaveValue(shifted)
})
