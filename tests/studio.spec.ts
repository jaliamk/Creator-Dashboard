test('portfolio adapts to a phone and applies dark appearance', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Projects', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Calendar', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Weekly production calendar' })).toBeVisible()
  expect(await page.locator('body').evaluate(body => body.scrollWidth)).toBeLessThanOrEqual(375)
  await page.getByRole('button', { name: 'Settings' }).click()
  await page.getByLabel('Appearance').selectOption('dark')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
})

